'use strict';
/* First-run seeding: loads the real NPI catalog from data/catalog.json
   (generated by scripts/build_catalog.py from the studio photos).
   Runs only while the database has no categories, so it never overwrites
   anything the owner has changed in the dashboard. */
const fs = require('node:fs');
const path = require('node:path');
const { db, tx } = require('./db');

const CATALOG = path.join(__dirname, '..', 'data', 'catalog.json');

function seedIfEmpty() {
  if (db.prepare('SELECT COUNT(*) AS n FROM categories').get().n) return false;
  if (!fs.existsSync(CATALOG)) {
    console.warn('data/catalog.json not found. Run: python3 scripts/build_catalog.py');
    return false;
  }
  const { categories, products } = JSON.parse(fs.readFileSync(CATALOG, 'utf8'));
  const now = Date.now();
  tx(() => {
    const insCat = db.prepare('INSERT INTO categories (slug, name, icon, sort_order, created_at, image, motion) VALUES (?, ?, ?, ?, ?, ?, ?)');
    const catIds = {};
    const firstImage = (slug) => products.find((p) => p.category === slug && p.images.length)?.images[0] || '';
    categories.forEach((c, i) => {
      catIds[c.slug] = Number(insCat.run(c.slug, c.name, 'wrench', i, now, firstImage(c.slug), c.motion || 'zoom').lastInsertRowid);
    });
    const insP = db.prepare(`INSERT INTO products
      (slug, sku, name, category_id, description, specs_json, uses_json, price, sale_price, stock, low_stock_threshold,
       icon, sim, motion, featured, active, bulk_min_qty, bulk_percent, images_json, video_url, sold_count,
       price_confirmed, created_at, updated_at)
      VALUES (?, ?, ?, ?, ?, ?, ?, ?, NULL, ?, 5, 'wrench', 'auto', 'auto', ?, 1, 0, 0, ?, '', 0, 0, ?, ?)`);
    const insMove = db.prepare(`INSERT INTO stock_movements (product_id, delta, stock_after, reason, ref, user_id, created_at)
                                VALUES (?, ?, ?, 'Opening stock', '', NULL, ?)`);
    const ids = [];
    products.forEach((p, i) => {
      const t = now - i; // keeps catalogue order stable for "newest"
      const id = Number(insP.run(p.slug, p.sku, p.name, catIds[p.category], p.description, JSON.stringify(p.specs),
        JSON.stringify(p.uses), p.price, p.stock, p.featured ? 1 : 0, JSON.stringify(p.images), t, t).lastInsertRowid);
      if (p.motion) db.prepare('UPDATE products SET motion = ? WHERE id = ?').run(p.motion, id);
      db.prepare('UPDATE products SET demo_json = ?, tags_json = ? WHERE id = ?').run(JSON.stringify(p.demo || {}), JSON.stringify(p.tags || []), id);
      insMove.run(id, p.stock, p.stock, t);
      ids.push(id);
    });
    // Weekly Jumma Deal: every Friday, all day, 15% off a few best-sellers. The owner can change or switch it off.
    const promoId = Number(db.prepare(`INSERT INTO promotions
      (name, badge, theme, discount_type, value, scope, category_id, days_of_week, start_time, end_time, starts_on, ends_on, active, created_at, updated_at)
      VALUES ('Jumma Deal', 'Jumma Deal', 'jumma', 'percent', 15, 'products', NULL, '5', NULL, NULL, NULL, NULL, 1, ?, ?)`).run(now, now).lastInsertRowid);
    const link = db.prepare('INSERT INTO promotion_products (promotion_id, product_id) VALUES (?, ?)');
    const pick = ['milestone-combination-pliers-orange-grip', 'npi-adjustable-wrench-black', 'npi-claw-hammer-fibreglass-handle', 'npi-measuring-tape-5-m-16-ft-np1008'];
    for (const slug of pick) {
      const row = db.prepare('SELECT id FROM products WHERE slug = ?').get(slug);
      if (row) link.run(promoId, row.id);
    }
  });
  console.log(`Loaded ${products.length} products in ${categories.length} categories from data/catalog.json`);
  return true;
}

module.exports = { seedIfEmpty };
